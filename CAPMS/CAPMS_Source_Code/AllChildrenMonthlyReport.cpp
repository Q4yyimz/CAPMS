void allChildrenMonthlyPerformanceReport(
    sql::Connection* con,
    const UserSession& session
)
{
    int reportMonth = 0;
    int reportYear = 0;
    int totalOperatingDays = 0;

    sql::PreparedStatement* operatingStatement = nullptr;
    sql::PreparedStatement* reportStatement = nullptr;

    sql::ResultSet* operatingResult = nullptr;
    sql::ResultSet* reportResult = nullptr;

    const string monthNames[12] =
    {
        "JANUARY", "FEBRUARY", "MARCH", "APRIL",
        "MAY", "JUNE", "JULY", "AUGUST",
        "SEPTEMBER", "OCTOBER", "NOVEMBER", "DECEMBER"
    };

    cout << "\n";
    cout << "============================================================\n";
    cout << "       ALL CHILDREN MONTHLY REPORT             \n";
    cout << "============================================================\n";
    cout << " Logged-In Administrator : "
         << session.staffName
         << " (" << session.staffId << ")\n";
    cout << "------------------------------------------------------------\n";

    cout << " Enter Report Month [1-12] : ";

    if (!(cin >> reportMonth))
    {
        cin.clear();
        clearInputBuffer();
        cout << "\nERROR: Please enter a valid month.\n";
        return;
    }

    if (reportMonth < 1 || reportMonth > 12)
    {
        clearInputBuffer();
        cout << "\nERROR: Month must be between 1 and 12.\n";
        return;
    }

    cout << " Enter Report Year         : ";

    if (!(cin >> reportYear))
    {
        cin.clear();
        clearInputBuffer();
        cout << "\nERROR: Please enter a valid year.\n";
        return;
    }

    clearInputBuffer();

    if (!isValidReportYear(reportYear))
    {
        cout << "\nERROR: Report year must be between 2020 and 2100.\n";
        return;
    }

    try
    {
        operatingStatement = con->prepareStatement(
            "SELECT COUNT(*) AS Total_Operating_Days "
            "FROM OPERATING_DAY "
            "WHERE MONTH(Operating_Date) = ? "
            "AND YEAR(Operating_Date) = ? "
            "AND Day_Status = 'OPEN'"
        );
        operatingStatement->setInt(1, reportMonth);
        operatingStatement->setInt(2, reportYear);
        operatingResult = operatingStatement->executeQuery();

        if (operatingResult->next())
        {
            totalOperatingDays =
                operatingResult->getInt("Total_Operating_Days");
        }

        reportStatement = con->prepareStatement(
            "SELECT "
            "c.Child_ID, c.Name AS Child_Name, "
            "COUNT(al.Log_ID) AS Total_Days_Present, "
            "SUM(CASE WHEN al.CheckOut_Points IS NOT NULL THEN 1 ELSE 0 END) AS Completed_Records, "
            "SUM(CASE WHEN al.Log_ID IS NOT NULL AND al.CheckOut_Points IS NULL THEN 1 ELSE 0 END) AS Pending_Records, "
            "SUM(CASE WHEN co.Status = 'LATE_PICKUP' THEN 1 ELSE 0 END) AS Late_Pickups, "
            "COALESCE(AVG(al.CheckIn_Points), 0.00) AS Average_CheckIn_Points, "
            "COALESCE(AVG(al.CheckOut_Points), 0.00) AS Average_CheckOut_Points, "
            "COALESCE(AVG(al.Daily_Points), 0.00) AS Average_Daily_Points, "
            "COALESCE(SUM(al.Late_Pickup_Charge), 0.00) AS Total_Late_Charges "
            "FROM CHILD c "
            "LEFT JOIN ATTENDANCE_LOG al "
            "ON c.Child_ID = al.Child_ID "
            "AND MONTH(al.Log_Date) = ? "
            "AND YEAR(al.Log_Date) = ? "
            "LEFT JOIN LOG_RECORD co "
            "ON al.Log_ID = co.Log_ID "
            "AND co.Record_Type = 'CHECK_OUT' "
            "GROUP BY c.Child_ID, c.Name "
            "ORDER BY "
            "CASE WHEN ? > 0 THEN COUNT(al.Log_ID) / ? ELSE 0 END DESC, "
            "COALESCE(AVG(al.Daily_Points), 0.00) DESC, "
            "c.Name ASC"
        );

        reportStatement->setInt(1, reportMonth);
        reportStatement->setInt(2, reportYear);
        reportStatement->setInt(3, totalOperatingDays);
        reportStatement->setInt(4, totalOperatingDays > 0 ? totalOperatingDays : 1);

        reportResult = reportStatement->executeQuery();

        vector<AllChildrenMonthlyRecord> records;

        int childrenWithAttendance = 0;
        int totalAttendanceRecords = 0;
        int totalLatePickupIncidents = 0;
        double totalMonthlyLateCharges = 0.0;

        while (reportResult->next())
        {
            AllChildrenMonthlyRecord record;

            record.childId =
                string(reportResult->getString("Child_ID").c_str());

            record.childName =
                string(reportResult->getString("Child_Name").c_str());

            record.operatingDays = totalOperatingDays;
            record.daysPresent =
                reportResult->getInt("Total_Days_Present");

            record.completedRecords =
                reportResult->isNull("Completed_Records")
                ? 0
                : reportResult->getInt("Completed_Records");

            record.pendingRecords =
                reportResult->isNull("Pending_Records")
                ? 0
                : reportResult->getInt("Pending_Records");

            record.latePickups =
                reportResult->isNull("Late_Pickups")
                ? 0
                : reportResult->getInt("Late_Pickups");

            record.totalLateCharges =
                reportResult->getDouble("Total_Late_Charges");

            record.daysAbsent =
                record.operatingDays - record.daysPresent;

            if (record.daysAbsent < 0)
            {
                record.daysAbsent = 0;
            }

            if (record.operatingDays > 0)
            {
                record.attendancePercentage =
                    static_cast<double>(record.daysPresent) /
                    static_cast<double>(record.operatingDays) * 100.0;
            }

            if (record.daysPresent > 0)
            {
                record.checkInPerformance =
                    reportResult->getDouble("Average_CheckIn_Points") * 100.0;

                childrenWithAttendance++;
            }

            if (record.completedRecords > 0)
            {
                record.checkOutPerformance =
                    reportResult->getDouble("Average_CheckOut_Points") * 100.0;

                record.overallPerformance =
                    reportResult->getDouble("Average_Daily_Points") * 100.0;
            }

            totalAttendanceRecords += record.daysPresent;
            totalLatePickupIncidents += record.latePickups;
            totalMonthlyLateCharges += record.totalLateCharges;

            records.push_back(record);
        }

        if (records.empty())
        {
            cout << "\nNo child records were found.\n";

            delete reportResult;
            delete reportStatement;
            delete operatingResult;
            delete operatingStatement;
            return;
        }

        cout << "\n";
        cout << "ALL CHILDREN MONTHLY PERFORMANCE RANKING\n";
        cout << "Period: "
             << monthNames[reportMonth - 1]
             << " " << reportYear << "\n\n";

        cout << left
             << setw(4) << "No"
             << setw(7) << "Child"
             << setw(18) << "Child Name"
             << setw(7) << "Open"
             << setw(9) << "Present"
             << setw(8) << "Absent"
             << setw(11) << "Attend %"
             << setw(10) << "In Perf"
             << setw(11) << "Out Perf"
             << setw(11) << "Overall"
             << setw(7) << "Late"
             << setw(11) << "Charges"
             << "\n";

        cout << string(114, '=') << "\n";

        int rowNumber = 0;

        for (const AllChildrenMonthlyRecord& record : records)
        {
            rowNumber++;

            const string attendanceText =
                record.operatingDays > 0
                ? formatAllChildrenNumber(record.attendancePercentage) + "%"
                : "N/A";

            const string checkInText =
                record.daysPresent > 0
                ? formatAllChildrenNumber(record.checkInPerformance) + "%"
                : "N/A";

            const string checkOutText =
                record.completedRecords > 0
                ? formatAllChildrenNumber(record.checkOutPerformance) + "%"
                : "N/A";

            const string overallText =
                record.completedRecords > 0
                ? formatAllChildrenNumber(record.overallPerformance) + "%"
                : "N/A";

            const string chargeText =
                "RM" + formatAllChildrenNumber(record.totalLateCharges);

            cout << left
                 << setw(4) << rowNumber
                 << setw(7) << record.childId
                 << setw(18) << shortChildName(record.childName, 16)
                 << setw(7) << record.operatingDays
                 << setw(9) << record.daysPresent
                 << setw(8) << record.daysAbsent
                 << setw(11) << attendanceText
                 << setw(10) << checkInText
                 << setw(11) << checkOutText
                 << setw(11) << overallText
                 << setw(7) << record.latePickups
                 << setw(11) << chargeText
                 << "\n";
        }

        cout << string(114, '=') << "\n";

        const AllChildrenMonthlyRecord& highest = records.front();
        const AllChildrenMonthlyRecord& lowest = records.back();

        cout << "\n";
        cout << "============================================================\n";
        cout << "                 MONTHLY REPORT SUMMARY                   \n";
        cout << "============================================================\n";
        cout << " Report Period               : "
             << monthNames[reportMonth - 1]
             << " " << reportYear << "\n";
        cout << " Total Registered Children   : "
             << records.size() << "\n";
        cout << " Children With Attendance    : "
             << childrenWithAttendance << "\n";
        cout << " Total Operating Days        : "
             << totalOperatingDays << "\n";
        cout << " Total Attendance Records    : "
             << totalAttendanceRecords << "\n";
        cout << " Total Late Pickup Incidents : "
             << totalLatePickupIncidents << "\n";
        cout << " Total Monthly Late Pickup Charges  : RM"
             << fixed << setprecision(2)
             << totalMonthlyLateCharges << "\n";
        cout << "------------------------------------------------------------\n";
        cout << " Highest Attendance          : "
             << highest.childId << " - "
             << highest.childName << " (";

        if (highest.operatingDays > 0)
        {
            cout << fixed << setprecision(2)
                 << highest.attendancePercentage << "%";
        }
        else
        {
            cout << "N/A";
        }

        cout << ")\n";
        cout << " Lowest Attendance           : "
             << lowest.childId << " - "
             << lowest.childName << " (";

        if (lowest.operatingDays > 0)
        {
            cout << fixed << setprecision(2)
                 << lowest.attendancePercentage << "%";
        }
        else
        {
            cout << "N/A";
        }

        cout << ")\n";
        cout << "============================================================\n";

        if (totalOperatingDays == 0)
        {
            cout << "\nNOTICE: No OPEN operating days were found "
                 << "for the selected month.\n";
            cout << "Attendance percentages are not available.\n";
        }

        int exportChoice = 0;

        while (true)
        {
            cout << "\nExport this All Children Monthly Report to PDF?\n";
            cout << " 1. Export PDF\n";
            cout << " 2. Return to Manage Reports\n";
            cout << "\n Select an option [1-2] : ";

            if (!(cin >> exportChoice))
            {
                cin.clear();
                clearInputBuffer();
                cout << "\nERROR: Please enter either 1 or 2.\n";
                continue;
            }

            clearInputBuffer();

            if (exportChoice == 1 || exportChoice == 2)
            {
                break;
            }

            cout << "\nERROR: Please select either 1 or 2.\n";
        }

        if (exportChoice == 1)
        {
            exportAllChildrenMonthlyPdf(
                records,
                reportMonth,
                reportYear,
                totalOperatingDays,
                childrenWithAttendance,
                totalAttendanceRecords,
                totalLatePickupIncidents,
                totalMonthlyLateCharges,
                session,
                monthNames[reportMonth - 1]
            );
        }

        delete reportResult;
        delete reportStatement;
        delete operatingResult;
        delete operatingStatement;
    }
    catch (sql::SQLException& e)
    {
        delete reportResult;
        delete reportStatement;
        delete operatingResult;
        delete operatingStatement;

        cerr << "\nSQL Error while generating All Children Monthly Report:\n";
        cerr << "Message    : " << e.what() << "\n";
        cerr << "Error Code : " << e.getErrorCode() << "\n";
        cerr << "SQL State  : " << e.getSQLState() << "\n";
    }
    catch (const exception& e)
    {
        delete reportResult;
        delete reportStatement;
        delete operatingResult;
        delete operatingStatement;

        cerr << "\nError while generating All Children Monthly Report:\n";
        cerr << e.what() << "\n";
    }
}
