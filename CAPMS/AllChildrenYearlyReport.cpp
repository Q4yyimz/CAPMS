void allChildrenYearlyPerformanceReport(
    sql::Connection* con,
    const UserSession& session
)
{
    int reportYear = 0;
    int yearlyOperatingDays = 0;
    int monthsWithOperatingCalendar = 0;

    sql::PreparedStatement* operatingStatement = nullptr;
    sql::PreparedStatement* reportStatement = nullptr;

    sql::ResultSet* operatingResult = nullptr;
    sql::ResultSet* reportResult = nullptr;

    cout << "\n";
    cout << "============================================================\n";
    cout << "        ALL CHILDREN YEARLY REPORT             \n";
    cout << "============================================================\n";
    cout << " Logged-In Administrator : "
         << session.staffName
         << " (" << session.staffId << ")\n";
    cout << "------------------------------------------------------------\n";

    cout << " Enter Report Year : ";

    if (!(cin >> reportYear))
    {
        cin.clear();
        clearInputBuffer();
        cout << "\nERROR: Please enter a valid year.\n";
        return;
    }

    clearInputBuffer();

    if (!isValidReportYear(reportYear))
    {
        cout << "\nERROR: Report year must be between 2020 and 2100.\n";
        return;
    }

    try
    {
        operatingStatement = con->prepareStatement(
            "SELECT "
            "COUNT(*) AS Total_Operating_Days, "
            "COUNT(DISTINCT MONTH(Operating_Date)) AS Calendar_Months "
            "FROM OPERATING_DAY "
            "WHERE YEAR(Operating_Date) = ? "
            "AND Day_Status = 'OPEN'"
        );

        operatingStatement->setInt(1, reportYear);
        operatingResult = operatingStatement->executeQuery();

        if (operatingResult->next())
        {
            yearlyOperatingDays =
                operatingResult->getInt("Total_Operating_Days");

            monthsWithOperatingCalendar =
                operatingResult->getInt("Calendar_Months");
        }

        reportStatement = con->prepareStatement(
            "SELECT "
            "c.Child_ID, c.Name AS Child_Name, "
            "COUNT(al.Log_ID) AS Total_Days_Present, "
            "SUM(CASE WHEN al.CheckOut_Points IS NOT NULL "
            "THEN 1 ELSE 0 END) AS Completed_Records, "
            "SUM(CASE WHEN al.Log_ID IS NOT NULL "
            "AND al.CheckOut_Points IS NULL "
            "THEN 1 ELSE 0 END) AS Pending_Records, "
            "SUM(CASE WHEN co.Status = 'LATE_PICKUP' "
            "THEN 1 ELSE 0 END) AS Late_Pickups, "
            "COALESCE(AVG(al.CheckIn_Points), 0.00) "
            "AS Average_CheckIn_Points, "
            "COALESCE(AVG(al.CheckOut_Points), 0.00) "
            "AS Average_CheckOut_Points, "
            "COALESCE(AVG(al.Daily_Points), 0.00) "
            "AS Average_Daily_Points, "
            "COALESCE(SUM(al.Late_Pickup_Charge), 0.00) "
            "AS Total_Late_Charges "
            "FROM CHILD c "
            "LEFT JOIN ATTENDANCE_LOG al "
            "ON c.Child_ID = al.Child_ID "
            "AND YEAR(al.Log_Date) = ? "
            "LEFT JOIN LOG_RECORD co "
            "ON al.Log_ID = co.Log_ID "
            "AND co.Record_Type = 'CHECK_OUT' "
            "GROUP BY c.Child_ID, c.Name "
            "ORDER BY "
            "CASE WHEN ? > 0 "
            "THEN COUNT(al.Log_ID) / ? ELSE 0 END DESC, "
            "COALESCE(AVG(al.Daily_Points), 0.00) DESC, "
            "c.Name ASC"
        );

        reportStatement->setInt(1, reportYear);
        reportStatement->setInt(2, yearlyOperatingDays);
        reportStatement->setInt(
            3,
            yearlyOperatingDays > 0 ? yearlyOperatingDays : 1
        );

        reportResult = reportStatement->executeQuery();

        vector<AllChildrenYearlyRecord> records;

        int childrenWithAttendance = 0;
        int totalAttendanceRecords = 0;
        int totalCompletedRecords = 0;
        int totalPendingRecords = 0;
        int totalLatePickupIncidents = 0;
        double totalYearlyLateCharges = 0.0;

        while (reportResult->next())
        {
            AllChildrenYearlyRecord record;

            record.childId =
                string(reportResult->getString("Child_ID").c_str());

            record.childName =
                string(reportResult->getString("Child_Name").c_str());

            record.operatingDays = yearlyOperatingDays;

            record.daysPresent =
                reportResult->getInt("Total_Days_Present");

            record.completedRecords =
                reportResult->isNull("Completed_Records")
                ? 0
                : reportResult->getInt("Completed_Records");

            record.pendingRecords =
                reportResult->isNull("Pending_Records")
                ? 0
                : reportResult->getInt("Pending_Records");

            record.latePickups =
                reportResult->isNull("Late_Pickups")
                ? 0
                : reportResult->getInt("Late_Pickups");

            record.totalLateCharges =
                reportResult->getDouble("Total_Late_Charges");

            record.daysAbsent =
                record.operatingDays - record.daysPresent;

            if (record.daysAbsent < 0)
            {
                record.daysAbsent = 0;
            }

            if (record.operatingDays > 0)
            {
                record.attendancePercentage =
                    static_cast<double>(record.daysPresent) /
                    static_cast<double>(record.operatingDays) * 100.0;
            }

            if (record.daysPresent > 0)
            {
                record.checkInPerformance =
                    reportResult->getDouble(
                        "Average_CheckIn_Points"
                    ) * 100.0;

                childrenWithAttendance++;
            }

            if (record.completedRecords > 0)
            {
                record.checkOutPerformance =
                    reportResult->getDouble(
                        "Average_CheckOut_Points"
                    ) * 100.0;

                record.overallPerformance =
                    reportResult->getDouble(
                        "Average_Daily_Points"
                    ) * 100.0;
            }

            totalAttendanceRecords += record.daysPresent;
            totalCompletedRecords += record.completedRecords;
            totalPendingRecords += record.pendingRecords;
            totalLatePickupIncidents += record.latePickups;
            totalYearlyLateCharges += record.totalLateCharges;

            records.push_back(record);
        }

        if (records.empty())
        {
            cout << "\nNo child records were found.\n";

            delete reportResult;
            delete reportStatement;
            delete operatingResult;
            delete operatingStatement;
            return;
        }

        cout << "\n";
        cout << "ALL CHILDREN YEARLY PERFORMANCE RANKING\n";
        cout << "Year: " << reportYear << "\n\n";

        cout << left
             << setw(4) << "No"
             << setw(7) << "Child"
             << setw(18) << "Child Name"
             << setw(7) << "Open"
             << setw(9) << "Present"
             << setw(8) << "Absent"
             << setw(11) << "Attend %"
             << setw(10) << "In Perf"
             << setw(11) << "Out Perf"
             << setw(11) << "Overall"
             << setw(7) << "Late"
             << setw(11) << "Charges"
             << "\n";

        cout << string(114, '=') << "\n";

        int rowNumber = 0;

        for (const AllChildrenYearlyRecord& record : records)
        {
            rowNumber++;

            const string attendanceText =
                record.operatingDays > 0
                ? formatAllChildrenYearlyNumber(
                    record.attendancePercentage
                ) + "%"
                : "N/A";

            const string checkInText =
                record.daysPresent > 0
                ? formatAllChildrenYearlyNumber(
                    record.checkInPerformance
                ) + "%"
                : "N/A";

            const string checkOutText =
                record.completedRecords > 0
                ? formatAllChildrenYearlyNumber(
                    record.checkOutPerformance
                ) + "%"
                : "N/A";

            const string overallText =
                record.completedRecords > 0
                ? formatAllChildrenYearlyNumber(
                    record.overallPerformance
                ) + "%"
                : "N/A";

            const string chargeText =
                "RM" + formatAllChildrenYearlyNumber(
                    record.totalLateCharges
                );

            cout << left
                 << setw(4) << rowNumber
                 << setw(7) << record.childId
                 << setw(18)
                 << shortenYearlyChildName(record.childName, 16)
                 << setw(7) << record.operatingDays
                 << setw(9) << record.daysPresent
                 << setw(8) << record.daysAbsent
                 << setw(11) << attendanceText
                 << setw(10) << checkInText
                 << setw(11) << checkOutText
                 << setw(11) << overallText
                 << setw(7) << record.latePickups
                 << setw(11) << chargeText
                 << "\n";
        }

        cout << string(114, '=') << "\n";

        const AllChildrenYearlyRecord& highest = records.front();
        const AllChildrenYearlyRecord& lowest = records.back();

        cout << "\n";
        cout << "============================================================\n";
        cout << "                  YEARLY REPORT SUMMARY                   \n";
        cout << "============================================================\n";
        cout << " Report Year                 : "
             << reportYear << "\n";
        cout << " Total Registered Children   : "
             << records.size() << "\n";
        cout << " Children With Attendance    : "
             << childrenWithAttendance << "\n";
        cout << " Total Operating Days        : "
             << yearlyOperatingDays << "\n";
        cout << " Calendar Months Available   : "
             << monthsWithOperatingCalendar << " / 12\n";
        cout << " Total Attendance Records    : "
             << totalAttendanceRecords << "\n";
        cout << " Completed Attendance Records: "
             << totalCompletedRecords << "\n";
        cout << " Pending Check-Out Records   : "
             << totalPendingRecords << "\n";
        cout << " Total Late Pickup Incidents : "
             << totalLatePickupIncidents << "\n";
        cout << " Total Yearly Late Pickup Charges   : RM"
             << fixed << setprecision(2)
             << totalYearlyLateCharges << "\n";
        cout << "------------------------------------------------------------\n";

        cout << " Highest Attendance          : "
             << highest.childId << " - "
             << highest.childName << " (";

        if (highest.operatingDays > 0)
        {
            cout << fixed << setprecision(2)
                 << highest.attendancePercentage << "%";
        }
        else
        {
            cout << "N/A";
        }

        cout << ")\n";

        cout << " Lowest Attendance           : "
             << lowest.childId << " - "
             << lowest.childName << " (";

        if (lowest.operatingDays > 0)
        {
            cout << fixed << setprecision(2)
                 << lowest.attendancePercentage << "%";
        }
        else
        {
            cout << "N/A";
        }

        cout << ")\n";
        cout << "============================================================\n";

        if (monthsWithOperatingCalendar < 12)
        {
            cout << "\nNOTICE: Operating calendars are available for "
                 << monthsWithOperatingCalendar
                 << " month(s) only.\n";

            cout << "Generate the remaining monthly calendars for "
                 << "a complete annual attendance percentage.\n";
        }

        int exportChoice = 0;

        while (true)
        {
            cout << "\nExport this All Children Yearly Report to PDF?\n";
            cout << " 1. Export PDF\n";
            cout << " 2. Return to Manage Reports\n";
            cout << "\n Select an option [1-2] : ";

            if (!(cin >> exportChoice))
            {
                cin.clear();
                clearInputBuffer();
                cout << "\nERROR: Please enter either 1 or 2.\n";
                continue;
            }

            clearInputBuffer();

            if (exportChoice == 1 || exportChoice == 2)
            {
                break;
            }

            cout << "\nERROR: Please select either 1 or 2.\n";
        }

        if (exportChoice == 1)
        {
            exportAllChildrenYearlyPdf(
                records,
                reportYear,
                yearlyOperatingDays,
                childrenWithAttendance,
                totalAttendanceRecords,
                totalCompletedRecords,
                totalPendingRecords,
                totalLatePickupIncidents,
                totalYearlyLateCharges,
                monthsWithOperatingCalendar,
                session
            );
        }

        delete reportResult;
        delete reportStatement;
        delete operatingResult;
        delete operatingStatement;
    }
    catch (sql::SQLException& e)
    {
        delete reportResult;
        delete reportStatement;
        delete operatingResult;
        delete operatingStatement;

        cerr << "\nSQL Error while generating All Children Yearly Report:\n";
        cerr << "Message    : " << e.what() << "\n";
        cerr << "Error Code : " << e.getErrorCode() << "\n";
        cerr << "SQL State  : " << e.getSQLState() << "\n";
    }
    catch (const exception& e)
    {
        delete reportResult;
        delete reportStatement;
        delete operatingResult;
        delete operatingStatement;

        cerr << "\nError while generating All Children Yearly Report:\n";
        cerr << e.what() << "\n";
    }
}
