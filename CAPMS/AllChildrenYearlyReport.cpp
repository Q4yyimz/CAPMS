struct AllChildrenYearlyRecord
{
    string childId;
    string childName;

    int operatingDays = 0;
    int daysPresent = 0;
    int daysAbsent = 0;
    int completedRecords = 0;
    int pendingRecords = 0;
    int latePickups = 0;

    double attendancePercentage = 0.0;
    double checkInPerformance = 0.0;
    double checkOutPerformance = 0.0;
    double overallPerformance = 0.0;
    double totalLateCharges = 0.0;
};

static string formatAllChildrenYearlyNumber(double value)
{
    ostringstream stream;
    stream << fixed << setprecision(2) << value;
    return stream.str();
}

static string shortenYearlyChildName(
    const string& name,
    size_t maximumLength
)
{
    if (name.length() <= maximumLength)
    {
        return name;
    }

    if (maximumLength <= 3)
    {
        return name.substr(0, maximumLength);
    }

    return name.substr(0, maximumLength - 3) + "...";
}

